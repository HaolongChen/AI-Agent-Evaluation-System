import { readFile, writeFile } from "node:fs/promises";
const SCHEMA_PATH = `${process.cwd()}/src/graphql/type/schema.graphql`;
const OUTPUT_PATH = `${process.cwd()}/src/graphql/type/TypeDefs.ts`;

const content = await readFile(SCHEMA_PATH, "utf8");

await writeFile(
  OUTPUT_PATH,
  `/* This file is auto-generated by scripts/graphql-schema-sync.ts. Do not edit manually. */
import { gql } from "graphql-tag";
export const typeDefs = gql\`
    ${content}
\`
`,
);
