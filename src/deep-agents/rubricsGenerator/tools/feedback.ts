import { tool } from "langchain";
import { logger } from "../../../utils/logger.ts";
import * as z from "zod";

export class Feedback {
	private feedbacks: string[] = [];
	readonly agentName: string;

	constructor(agentName: string) {
		this.agentName = agentName;
	}

	addFeedback(feedback: string) {
		this.feedbacks.push(feedback);
		logger.debug(`Added feedback: ${feedback}`);
	}

	getFeedbacks(): string[] {
		return this.feedbacks;
	}
}

export const save_agent_feedbacks = tool(
	({ feedbacks }, options) => {
		try {
			switch (options?.metadata?.lc_agent_name) {
				case "RubricsGeneratorAgent":
					options.context.rubricsGeneratorAgent.addFeedback(feedbacks);
					break;
				case "SchemaLookupAgent":
					options.context.schemaLookupAgent.addFeedback(feedbacks);
					break;
				case "DocsLookupAgent":
					options.context.docsLookupAgent.addFeedback(feedbacks);
					break;
				default:
					logger.warn(
						`Unknown agent name: ${options.metadata.lc_agent_name}. Feedback not saved.`,
					);
			}
			return {
				message: "Feedback saved successfully",
			};
		} catch (error) {
			logger.error("Error saving agent feedbacks:", error);
			logger.debug("options", options);
			return {
				error:
					"Failed to save agent feedbacks. Stop now!!! Ask your sub-agents or main agents to stop!!!",
			};
		}
	},
	{
		name: "save_agent_feedbacks",
		description:
			"Save feedbacks for agents. This tool is used to store the feedback generated by evaluation agents during the evaluation process. The feedback can be used for further analysis and improvement of the agents. The input should include the feedback content and the agent name, which will be used to associate the feedback with the correct agent.",
		schema: z.object({
			feedbacks: z
				.string()
				.describe("The feedback content to be saved for the agent."),
		}),
	},
);
